"""Generate the acceptance fixture pair.

``tests/wrd_v1_0_0.lua`` is written in the *shape* of a WeAreDevs v1.0.0 build
(the shape Excalibur's detector and static layer were written against):

* the ``--[[ v1.0.0 https://wearedevs.net/obfuscator ]]`` banner,
* ``return(function(...) ... end)(...)`` wrapper,
* a string pool of escaped-decimal literals that are custom-alphabet base64,
* a ``{char = value}`` alphabet table,
* a pool resolver ``function h(x) return j[x - OFFSET] end``,
* constant-folding bait (``h(1000 + 5)``, ``812345 - 812342``),
* a dispatch-style ``while`` loop, and
* the payload rebuilt at runtime with ``table.concat`` and executed with
  ``loadstring`` - the case the dynamic stage exists for.

The pair is generated from ``tests/wrd_v1_0_0_clean.lua`` and only depends on
that file plus a fixed alphabet/offset, so regenerating is deterministic:

    python tools/make_wrd_fixture.py            # write both files
    python tools/make_wrd_fixture.py --check    # fail if they are out of date
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path
from typing import List, Sequence, Tuple

ROOT = Path(__file__).resolve().parent.parent
CLEAN = ROOT / "tests" / "wrd_v1_0_0_clean.lua"
OBFUSCATED = ROOT / "tests" / "wrd_v1_0_0.lua"

HEADER = "--[[ v1.0.0 https://wearedevs.net/obfuscator ]]"
BANNER_NOTE = "-- generated by tools/make_wrd_fixture.py - do not edit by hand"

#: The custom base64 alphabet used by this build (64 distinct characters).
ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz+/"
#: Resolver offset: ``h(x)`` reads ``j[x - OFFSET]``.
OFFSET = 1000
#: Chunk size for splitting the payload into pool entries.
CHUNK = 48

#: Variable names are randomised per build; these stand in for them.
POOL_VAR = "u"
TABLE_VAR = "j"
MAP_VAR = "a"
DECODED_VAR = "z"
RESOLVER_VAR = "h"
STAGE_VAR = "s"


def escape_bytes(data: bytes) -> str:
    """Render ``data`` as a Lua short string with ``\\ddd`` escapes."""
    return "".join(f"\\{byte:03d}" for byte in data)


def encode_entry(data: bytes, alphabet: str) -> str:
    """Custom-alphabet base64 (``=`` padded), matching the WRD pool format."""
    table = {char: index for index, char in enumerate(alphabet)}
    reverse = {index: char for char, index in table.items()}
    out: List[str] = []
    for start in range(0, len(data), 3):
        block = data[start : start + 3]
        accumulator = int.from_bytes(block, "big") << (8 * (3 - len(block)))
        padded = (len(block) % 3) or 3
        digits = [
            (accumulator >> 18) & 0x3F,
            (accumulator >> 12) & 0x3F,
            (accumulator >> 6) & 0x3F,
            accumulator & 0x3F,
        ]
        for index in range(padded + 1):
            out.append(reverse[digits[index]])
        out.append("=" * (4 - (padded + 1)))
    return "".join(out)


def chunk_payload(source: str, *, size: int = CHUNK) -> List[bytes]:
    data = source.encode("latin-1", "replace")
    return [data[index : index + size] for index in range(0, len(data), size)]


def build_obfuscated(clean: str) -> str:
    chunks = chunk_payload(clean)
    pool_items = ",\n".join(
        f'  "{escape_bytes(encode_entry(chunk, ALPHABET).encode("latin-1"))}"' for chunk in chunks
    )

    alphabet_items = ",\n".join(
        f'  ["{char}"]={index}' for index, char in enumerate(ALPHABET)
    )

    lines = [
        HEADER,
        BANNER_NOTE,
        "return(function(...)",
        f"local {POOL_VAR}={{{pool_items}}}",
        f"local {MAP_VAR}={{{alphabet_items}}}",
        f"local {TABLE_VAR}={{}}",
        f"local {RESOLVER_VAR}=function({chr(105)})return {TABLE_VAR}[{chr(105)}-{OFFSET}]end",
        f"local tag={RESOLVER_VAR}({OFFSET}+1)",
        f"local other={RESOLVER_VAR}({OFFSET}+2)",
        f"local folded={RESOLVER_VAR}(812345-812342+{OFFSET - 999})",
        f"local limit=812345-812342+{OFFSET}",
        f"local {STAGE_VAR}=1",
        "while " + STAGE_VAR + " do",
        f"  if {STAGE_VAR}==1 then",
        f"    for k=1,#{POOL_VAR} do",
        f"      local text={POOL_VAR}[k]",
        "      local bytes={}",
        "      local acc,n=0,0",
        f"      for index=1,#text do",
        f"        local ch=text:sub(index,index)",
        f'        if ch~="=" then',
        f"          local digit={MAP_VAR}[ch]",
        "          if digit then",
        "          acc=acc*64+digit",
        "          n=n+1",
        "          if n==4 then",
        "            bytes[#bytes+1]=string.char(math.floor(acc/65536)%256,math.floor(acc/256)%256,acc%256)",
        "            acc,n=0,0",
        "          end",
        "          end",
        "        end",
        "      end",
        "      if n==3 then",
        "        local value=math.floor(acc/4)",
        "        bytes[#bytes+1]=string.char(math.floor(value/256)%256,value%256)",
        "      elseif n==2 then",
        "        bytes[#bytes+1]=string.char(math.floor(acc/16)%256)",
        "      end",
        f"      {TABLE_VAR}[k]=table.concat(bytes)",
        "    end",
        f"    {STAGE_VAR}=2",
        f"  elseif {STAGE_VAR}==2 then",
        f"    local parts={{}}",
        f"    for k=1,#{POOL_VAR} do parts[k]={RESOLVER_VAR}({OFFSET}+k) end",
        "    local source=table.concat(parts)",
        f"    local chunk=loadstring(source)",
        "    if chunk then return chunk(...) end",
        f"    {STAGE_VAR}=nil",
        "  else",
        f"    {STAGE_VAR}=nil",
        "  end",
        "end",
        "return nil",
        "end)(...)",
        "",
    ]
    return "\n".join(lines)


def sha1(text: str) -> str:
    return hashlib.sha1(text.encode("utf-8", "replace")).hexdigest()


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="generate the WRD acceptance fixture")
    parser.add_argument("--check", action="store_true", help="verify the committed fixture matches")
    parser.add_argument("--print", action="store_true", help="print instead of writing")
    args = parser.parse_args(argv)

    clean = CLEAN.read_text(encoding="utf-8")
    obfuscated = build_obfuscated(clean)

    if args.print:
        print(obfuscated)
        return 0

    if args.check:
        current = OBFUSCATED.read_text(encoding="utf-8") if OBFUSCATED.exists() else ""
        if current != obfuscated:
            print("tests/wrd_v1_0_0.lua is out of date: run python tools/make_wrd_fixture.py")
            return 1
        print(f"fixture up to date ({len(obfuscated)} bytes, sha1 {sha1(obfuscated)[:12]})")
        return 0

    OBFUSCATED.write_text(obfuscated, encoding="utf-8")
    print(f"wrote {OBFUSCATED.relative_to(ROOT)} ({len(obfuscated)} bytes, sha1 {sha1(obfuscated)[:12]})")
    print(f"clean payload: {len(clean)} bytes, sha1 {sha1(clean)[:12]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
